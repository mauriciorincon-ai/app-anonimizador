/** Quita tildes y pasa a minúsculas para que "MARÍA", "maria" y "María" sean el mismo token. */
export function normalizarToken(texto: string): string {
  return texto.normalize("NFD").replace(/[\u0300-\u036f]/g, "").toLowerCase();
}

