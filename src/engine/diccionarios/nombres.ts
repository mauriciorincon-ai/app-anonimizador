const LEXICO = new Set([...NOMBRES_DE_PILA, ...APELLIDOS]);

/** Partículas que unen apellidos compuestos ("de la Torre") y no cuentan como token con carga. */
const PARTICULAS = new Set([
  "de",
  "del",
  "la",
  "las",
  "los",
  "y",
  "san",
  "santa",
]);

/** ¿Es un nombre propio de persona? Expuesto aparte para que los tests lo usen sin el validador. */
export function pareceNombreDePersona(valor: string): boolean {
  const limpio = valor.trim();
  if (limpio.length < 3 || limpio.length > 80) return false;
  // Solo letras (con tildes y ñ), espacios, apóstrofos y guiones: un nombre no lleva dígitos.
  if (!/^[\p{L}][\p{L}\s'’-]*$/u.test(limpio)) return false;

  const tokens = limpio.split(/\s+/).map(normalizarToken);
  if (tokens.length < 1 || tokens.length > 6) return false;

  const conCarga = tokens.filter((t) => !PARTICULAS.has(t));
  if (conCarga.length === 0) return false;
  return conCarga.some((token) => LEXICO.has(token));
}

